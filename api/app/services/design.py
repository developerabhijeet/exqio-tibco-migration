"""Tab 4, Design: the design record job (deterministic skeleton, then the designer's narrative) and
its view.

Code builds the skeleton (``engine.dotnet_gen.design.build_design_skeleton``): solution layout, the
mapping of every TIBCO step to a C# file, class and method, contracts, configuration, messaging,
resilience, sequence and expected differences, bound to the process's spec hash. The Solution
Designer (a model) only writes the narrative, decisions and open questions, which are outside the
design hash; with no provider the record is stored without them and the job says so.

A new record whose design hash differs from the previous one resets G3 to G6 (``design record
changed``).
"""
from __future__ import annotations

import asyncio
from datetime import UTC, datetime
from typing import Any

from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from api.app.config import Settings
from api.app.jobs.runner import JobContext
from api.app.models import DesignRecord, Process
from api.app.services import evidence
from api.app.services import gates as gate_svc
from api.app.services.context import engine_app, engine_findings, engine_process, engine_rules
from api.app.services.knowledge import Knowledge, KnowledgeUnavailable
from api.app.services.process_views import io_card_for
from api.app.services.providers import build_provider, model_call_recorder, stage_of
from engine.agents.designer import DesignHashChanged, design_narrative
from engine.agents.jsonout import JsonOutputError
from engine.agents.provider import ProviderError
from engine.agents.routing import ModelCallRecord
from engine.dotnet_gen.design import build_design_skeleton

STAGES = ["skeleton", "memory", "designer", "persist"]
SKIPPED = "skipped: no model configured, the design record is stored without narrative"
RESET_REASON = "design record changed"


def design_job(process_id: str, settings: Settings, knowledge: Knowledge):
    async def run(ctx: JobContext) -> dict[str, Any]:
        return await run_design(ctx, process_id, settings, knowledge)

    return run


def ai_logger(ctx: JobContext):
    async def on_record(rec: ModelCallRecord) -> None:
        state = "failed: " + (rec.error or "") if rec.error else (
            f"{rec.usage.get('in', 0)} tokens in, {rec.usage.get('out', 0)} out")
        await ctx.log(f"model call {stage_of(rec)}: {rec.provider} {rec.model or '-'} (tier {rec.tier}, "
                      f"task complexity {rec.complexity:g}{', after fallback' if rec.fell_back else ''}); "
                      f"{state}", tag="ai")

    return on_record


async def run_design(ctx: JobContext, process_id: str, settings: Settings,
                     knowledge: Knowledge) -> dict[str, Any]:
    async with ctx.sessionmaker() as s:
        row = await s.get(Process, process_id)
        if row is None:
            raise ValueError(f"process {process_id} not found")
        app = await engine_app(s, row)
        proc = engine_process(app, row)
        rules = await engine_rules(s, process_id)
        findings = await engine_findings(s, process_id)
        card = await io_card_for(s, row)
        spec = row.spec_hash
        project_id = row.project_id

    await ctx.stage(STAGES[0])
    design = await asyncio.to_thread(build_design_skeleton, proc, app, rules, findings, card, spec)
    agent_rows = sum(1 for r in design.mapping if r.origin == "agent")
    await ctx.log(f"mapping: {len(design.mapping)} row(s), {len(design.mapping) - agent_rows} generated by "
                  f"code, {agent_rows} left to the Code Builder")
    await ctx.log(f"{len(design.contracts)} contract(s), {len(design.config)} configuration key(s), "
                  f"{len(design.messaging)} messaging entit(ies), {len(design.sequence)} sequence step(s), "
                  f"{len(design.expected_differences)} expected difference(s); design hash "
                  f"{design.design_hash[:12]} bound to spec hash {(spec or '')[:12]}")

    choice = build_provider(settings, process=proc)
    provider = choice.provider
    if provider is not None:
        provider.recorder = model_call_recorder(
            ctx.sessionmaker, job_id=ctx.job_id, project_id=project_id, process_id=process_id,
            primary_name=provider.primary.name, on_record=ai_logger(ctx))

    await ctx.stage(STAGES[1])
    memory_items: list[Any] = []
    if provider is None:
        await ctx.log("migration memory not needed: no model will read it")
    else:
        try:
            memory_items = await knowledge.retrieve_memory(project_id, f"{proc.name} design decisions")
            await ctx.log(f"{len(memory_items)} prior decision(s) or pattern(s) from migration memory "
                          "passed to the designer")
        except KnowledgeUnavailable as exc:
            await ctx.log(f"migration memory unavailable: {exc}")

    await ctx.stage(STAGES[2])
    ai_error: str | None = None
    if provider is None:
        await ctx.log(SKIPPED, tag="ai")
    else:
        try:
            design = await design_narrative(design, proc, rules, findings, memory_items, provider,
                                            app.contracts)
            await ctx.log(f"Solution Designer wrote the narrative, {len(design.decisions)} decision(s) and "
                          f"{len(design.open_questions)} open question(s); design hash unchanged", tag="ai")
        except (ProviderError, JsonOutputError, DesignHashChanged) as exc:
            ai_error = str(exc)
            await ctx.log(f"Solution Designer failed, the record is stored without narrative: {exc}",
                          tag="ai")

    await ctx.stage(STAGES[3])
    async with ctx.sessionmaker() as s:
        process = await s.get(Process, process_id)
        previous = await evidence.latest_design(s, process_id)
        version = (await s.scalar(select(func.max(DesignRecord.version))
                                  .where(DesignRecord.process_id == process_id)) or 0) + 1
        record = DesignRecord(process_id=process_id, version=version, job_id=ctx.job_id,
                              spec_hash=design.spec_hash, design_hash=design.design_hash,
                              record=design.model_dump(mode="json", by_alias=True),
                              narrative=design.narrative)
        s.add(record)
        reset: list[str] = []
        if previous is not None and previous.design_hash != design.design_hash:
            rows = await gate_svc.gate_rows(s, process_id)
            reset = await gate_svc.reset_gates(
                s, process, rows, "G3", RESET_REASON, gate_svc.SYSTEM, gate_svc.SYSTEM,
                {"old_design_hash": previous.design_hash, "new_design_hash": design.design_hash})
        gate_svc.audit(s, process, gate_svc.SYSTEM, "design generated", actor_kind=gate_svc.SYSTEM,
                       detail={"version": version, "design_hash": design.design_hash,
                               "spec_hash": design.spec_hash, "job_id": ctx.job_id})
        await s.commit()
        design_id = record.id
    await ctx.log(f"stored design record v{version}" + (f"; gates reset: {', '.join(reset)}" if reset else ""))
    return {"design_id": design_id, "version": version, "design_hash": design.design_hash,
            "spec_hash": design.spec_hash, "mapping_rows": len(design.mapping), "agent_rows": agent_rows,
            "decisions": len(design.decisions), "open_questions": len(design.open_questions),
            "ai_available": provider is not None and ai_error is None,
            "ai_reason": choice.reason or ai_error, "provider": choice.name, "gates_reset": reset}


async def answer_open_question(session: AsyncSession, process: Process, index: int,
                               decision: str | None, answer: str | None, user: str) -> dict[str, Any]:
    """Answer or reject one open question on the latest design record, and return the design view.

    The verdict is written into the record's ``open_questions``, which ``HASH_EXCLUDED`` keeps out
    of the design hash: settling a question is a note on the design, not a change to it, so an
    approved G3 stays approved. A later design job writes its own questions and starts clean."""
    row = await evidence.latest_design(session, process.id)
    if row is None:
        raise LookupError("no design record yet")
    record = dict(row.record)
    questions = [dict(q) for q in record.get("open_questions") or []]
    if index < 0 or index >= len(questions):
        raise IndexError(index)
    q = questions[index]
    if decision is None:
        for key in ("decision", "answer", "decided_by", "decided_at"):
            q.pop(key, None)
    else:
        q["decision"] = decision
        q["answer"] = (answer or "").strip()
        q["decided_by"] = user
        q["decided_at"] = datetime.now(UTC).isoformat()
    record["open_questions"] = questions
    row.record = record  # a new dict, so SQLAlchemy sees the JSONB change
    await session.commit()
    return await design_view(session, process)


async def design_view(session: AsyncSession, process: Process) -> dict[str, Any] | None:
    """The latest design record (engine ``DesignRecord`` fields) plus its row metadata."""
    row = await evidence.latest_design(session, process.id)
    if row is None:
        return None
    stale = row.spec_hash != process.spec_hash
    return {**row.record, "narrative": row.narrative, "id": row.id, "version": row.version,
            "job_id": row.job_id, "created_at": row.created_at.isoformat() if row.created_at else None,
            "current_spec_hash": process.spec_hash, "stale": stale,
            "stale_reason": "the spec hash changed since this record was generated" if stale else None}

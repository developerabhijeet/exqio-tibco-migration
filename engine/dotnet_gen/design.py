CONFIG_ROOT = "Gmf"
pascal = csharp_contracts.pascal

_PROJECT_KINDS = (("Api", "api"), ("Core", "core"), ("Infrastructure", "infrastructure"), ("Tests", "tests"))
_PROJECT_SUFFIX = {kind: suffix for suffix, kind in _PROJECT_KINDS}
_API_STARTERS = ("rest", "http", "soap")
_JMS_TYPES = ("jms.receive", "jms.send", "jms.publish", "jms.reply", "jms.request_reply")
_INVOKE_TYPES = ("http.invoke", "rest.invoke", "soap.invoke")
_LIVE_RULES = ("draft", "approved", "edited", "unverified")
_NOT_A_DECISION = "A recommendation, not a decision: the architect decides at G3."


# ------------------------------------------------------------------- helpers
def _ident(name: str, fallback: str = "Step") -> str:
    p = pascal(name)
    if not p:
        return fallback
    return f"{fallback}{p}" if p[0].isdigit() else p


def _find_resource(app: Application, ref: Any) -> Resource | None:
    if not isinstance(ref, str) or not ref:
        return None
    for r in app.resources:
        if r.id == ref:
            return r
    hits = [r for r in app.resources if r.id.endswith("." + ref) or r.id.endswith("/" + ref)]
    return hits[0] if len(hits) == 1 else None


def _destination(act: Activity) -> str:
    c = act.config
    settings = c.get("settings") if isinstance(c.get("settings"), dict) else {}
    return str(c.get("destination") or settings.get("destination") or "")


def _messaging_style(act: Activity) -> str:
    c = act.config
    settings = c.get("settings") if isinstance(c.get("settings"), dict) else {}
    return str(c.get("messaging_style") or settings.get("messagingStyle") or "").lower()


_SIMPLE_PATH = re.compile(r"^\$[\w.\-]+(/@?[\w.\-]+(:[\w.\-]+)?(\[\d+\])?)*$")
_LITERAL = re.compile(r"""^("[^"]*"|'[^']*'|-?\d+(\.\d+)?)$""")


def is_simple_expression(expr: str) -> bool:
    """A plain variable path or a literal: generated by code. Anything else goes to the agent."""
    e = (expr or "").strip()
    return bool(_SIMPLE_PATH.match(e) or _LITERAL.match(e))


# -------------------------------------------------------------------- secrets
_SECRET_TOKENS = {"password", "passwd", "pwd", "secret", "secrets", "token", "key", "apikey",
                  "credential", "credentials", "privatekey", "passphrase", "sas"}
_SECRET_FRAGMENTS = ("connectionstring", "connstr", "connstring", "password", "secret", "apikey",
                     "accesskey", "privatekey")
_SECRET_VALUE = re.compile(
    r"(?i)(password|pwd|secret|token|apikey|api_key|accountkey|sharedaccesskey)\s*="
    r"|^\s*jdbc:"
    r"|^\s*(server|host|data source)\s*=[^;]*;"
    r"|endpoint\s*=\s*sb://"
    r"|://[^/\s:@]+:[^/\s@]+@"
    r"|^\s*eyJ[\w-]+\.[\w-]+\."
    r"|-----BEGIN"
)


def _name_tokens(name: str) -> list[str]:
    return [t.lower() for t in re.findall(r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|\d+", name)]


def looks_secret(name: str, value: str = "") -> bool:
    """True when a substvar name or value looks like a password, secret, key, token or connection string."""
    toks = _name_tokens(name)
    joined = "".join(toks)
    if _SECRET_TOKENS & set(toks) or any(f in joined for f in _SECRET_FRAGMENTS):
        return True
    return bool(value and _SECRET_VALUE.search(value))


# ---------------------------------------------------------------------- rows
class _Ctx:
    def __init__(self, process: Process, app: Application, rules: list[Rule], findings: list[Finding]):
        self.p = process
        self.app = app
        self.app_name = _ident(app.id, "App")
        self.proc_name = _ident(process.name, "Process")
        self.module = _ident(process.module or app.id, "Module")
        self.starter = process.starter
        self.starter_kind = process.starter.kind if process.starter else None
        acts = {a.id: a for a in process.activities}
        st_act = acts.get(process.starter.activity_id) if process.starter else None
        self.starter_name = _ident(st_act.name if st_act else "Execute")
        self.calls = {c.activity_id: c.target_process for c in process.calls}
        self.rules_by: dict[str, list[str]] = defaultdict(list)
        for r in rules:
            if r.status not in _LIVE_RULES:
                continue
            for c in r.citations:
                if r.id not in self.rules_by[c.activity_id]:
                    self.rules_by[c.activity_id].append(r.id)
        self.findings_by: dict[str, list[str]] = defaultdict(list)
        for f in findings:
            for c in f.citations:
                if f.id not in self.findings_by[c.activity_id]:
                    self.findings_by[c.activity_id].append(f.id)

    def project(self, kind: str) -> str:
        return f"{self.app_name}.{_PROJECT_SUFFIX[kind]}"

    def values(self, act: Activity | None, name: str) -> dict[str, str]:
        resource = name
        fault = f"{_ident(name)}Exception"
        target = ""
        destination = ""
        if act is not None:
            res = _find_resource(self.app, act.config.get("resource_ref"))
            raw = res.name if res else str(act.config.get("resource_ref") or name).rsplit(".", 1)[-1]
            resource = _ident(raw)
            if resource.endswith("Client") and len(resource) > len("Client"):
                resource = resource[: -len("Client")]
            if act.config.get("fault_name"):
                fault = _ident(str(act.config["fault_name"]))
            tgt = self.calls.get(act.id) or act.config.get("sub_process") or act.config.get("subprocess") or ""
            target = _ident(str(tgt).rsplit(".", 1)[-1]) if tgt else ""
            destination = _destination(act)
        return {"app": self.app_name, "process": self.proc_name, "activity": _ident(name),
                "starter": self.starter_name, "resource": resource, "fault": fault,
                "target": target, "destination": destination}

    def row(self, node_id: str, name: str, ctype: str, pattern: str, spec: PatternSpec,
            act: Activity | None, origin: str | None = None) -> MappingRow:
        v = self.values(act, name)
        project, file_t, class_t, method_t = spec.project, spec.file_template, spec.class_template, spec.method_template
        if pattern == "reply":
            if self.starter_kind == "soap":
                file_t, class_t = "Soap/{process}SoapService.cs", "{process}SoapService"
            elif self.starter_kind not in _API_STARTERS:
                project, file_t, class_t, method_t = ("core", "Services/{process}Service.cs",
                                                      "{process}Service", "ExecuteAsync")
        if pattern == "call.process" and not v["target"]:
            v["target"] = v["activity"]
        return MappingRow(
            activity_id=node_id, activity_name=name, canonical_type=ctype, pattern=pattern,
            project=self.project(project), file=file_t.format(**v), class_name=class_t.format(**v),
            method=method_t.format(**v), rule_ids=list(self.rules_by.get(node_id, [])),
            finding_ids=list(self.findings_by.get(node_id, [])), origin=origin or spec.origin,
        )


def _activity_rows(ctx: _Ctx, act: Activity) -> list[MappingRow]:
    pattern = act.type if act.type in PATTERNS else "unknown"
    spec = PATTERNS[pattern]
    origin = None
    if pattern in ("mapper", "assign"):
        origin = "code" if all(is_simple_expression(b.expression) for b in act.input_bindings) else "agent"
    rows = [ctx.row(act.id, act.name or act.id, act.type, pattern, spec, act, origin)]
    if pattern not in ("mapper", "assign") and act.input_bindings:
        simple = all(is_simple_expression(b.expression) for b in act.input_bindings)
        rows.append(ctx.row(act.id, act.name or act.id, act.type, "input.mapping", PATTERNS["input.mapping"],
                            act, "code" if simple else "agent"))
    return rows


def _group_row(ctx: _Ctx, g: Group) -> MappingRow | None:
    ctype = GROUP_KIND_TO_CANONICAL.get(g.kind)
    if not ctype:
        return None
    return ctx.row(g.id, g.id, ctype, ctype, PATTERNS[ctype], None)


# ----------------------------------------------------------------- contracts
_HREF = re.compile(r"platform:/resource/([^#\"']+)")


def _process_contracts(process: Process, app: Application, card: IOCard) -> list[Contract]:
    by_id = {c.id: c for c in app.contracts}
    ids: list[str] = [i for i in process.contracts_used if i in by_id]
    for act in process.activities:
        for m in _HREF.finditer(json.dumps(act.config, sort_keys=True)):
            if m.group(1) in by_id:
                ids.append(m.group(1))
    names: list[str] = []
    for act in process.activities:
        if act.config.get("fault_name"):
            names.append(str(act.config["fault_name"]))
    names += [h.fault_name for h in process.fault_handlers if h.fault_name]
    for tree in (card.request_contract, card.response_contract):
        if isinstance(tree, dict) and tree.get("name"):
            names.append(str(tree["name"]))
    prefix = f"{process.module}/" if process.module else ""
    for name in names:
        hits = [c.id for c in app.contracts if name in c.root_elements]
        local = [h for h in hits if prefix and h.startswith(prefix)]
        if any(h in ids for h in hits):
            continue
        pick = local or (hits if len(hits) == 1 else [])
        ids += pick[:1]
    return [by_id[i] for i in sorted(set(ids))]


# --------------------------------------------------------------------- config
def _substvar_module(name: str, source_path: str) -> tuple[str | None, str]:
    if name.startswith("//") and "//" in name[2:]:
        module, rest = name[2:].split("//", 1)
        return module, rest
    parts = PurePath(source_path.replace("\\", "/")).parts if source_path else ()
    for marker in ("META-INF", "defaultVars"):
        if marker in parts:
            i = parts.index(marker)
            if i > 0:
                return parts[i - 1], name
    return None, name


def _config(ctx: _Ctx, resources: list[Resource]) -> list[ConfigMap]:
    p, app = ctx.p, ctx.app
    chosen: dict[str, tuple[int, str]] = {}  # name -> (precedence, value)
    for sv in app.substvars:
        module, name = _substvar_module(sv.name, sv.source_path)
        if module is not None and len(app.modules) > 1 and p.module and module != p.module:
            continue
        precedence = 1 if sv.name.startswith("//") else 0  # application level overrides module level
        if name not in chosen or precedence > chosen[name][0]:
            chosen[name] = (precedence, sv.value)
    rows = [ConfigMap(substvar=name, key=f"{CONFIG_ROOT}:{ctx.module}:{_ident(name, 'Var')}",
                      secret=looks_secret(name, value))
            for name, (_, value) in sorted(chosen.items())]
    for res in resources:
        rname = _ident(res.name, "Resource")
        for fld in res.masked_fields:
            rows.append(ConfigMap(substvar=f"resource:{res.name}.{fld}",
                                  key=f"{CONFIG_ROOT}:{ctx.module}:{rname}:{_ident(fld, 'Setting')}", secret=True))
        if res.kind == "jdbc":
            rows.append(ConfigMap(substvar=f"resource:{res.name}.jdbc_url", key=f"ConnectionStrings:{rname}",
                                  secret=True))
    return rows


def _used_resources(p: Process, app: Application) -> list[Resource]:
    refs: list[Any] = []
    if p.starter:
        refs += [p.starter.config.get(k) for k in ("resource_ref", "connector")]
    for act in p.activities:
        refs += [act.config.get(k) for k in ("resource_ref", "connector")]
    found: dict[str, Resource] = {}
    for ref in refs:
        res = _find_resource(app, ref)
        if res:
            found[res.id] = res
    return [found[k] for k in sorted(found)]


# ------------------------------------------------------------------ messaging
def _messaging(p: Process) -> list[MessagingEntity]:
    out: list[MessagingEntity] = []

    def add(kind: str, name: str, direction: str) -> None:
        e = MessagingEntity(kind=kind, name=name, direction=direction)  # type: ignore[arg-type]
        if name and e not in out:
            out.append(e)

    for act in p.activities:
        if act.type not in _JMS_TYPES or act.type == "jms.reply":
            continue
        dest, style = _destination(act), _messaging_style(act)
        if act.type == "jms.receive":
            if style == "topic":
                add("topic", dest, "in")
                add("subscription", f"{dest}/{p.name}", "in")
            else:
                add("queue", dest, "in")
        elif act.type == "jms.publish":
            add("queue" if style == "queue" else "topic", dest, "out")
        else:  # jms.send, jms.request_reply
            add("topic" if style == "topic" else "queue", dest, "out")
    return out


# ----------------------------------------------------------------- resilience
def _int(v: Any) -> int | None:
    if isinstance(v, bool):
        return None
    if isinstance(v, int):
        return v
    if isinstance(v, str) and re.fullmatch(r"-?\d+", v.strip()):
        return int(v.strip())
    return None


def _resilience(p: Process, app: Application) -> list[ResilienceMap]:
    out: dict[str, ResilienceMap] = {}
    for act in p.activities:
        if act.type not in _INVOKE_TYPES:
            continue
        res = _find_resource(app, act.config.get("resource_ref"))
        if res is None or res.id in out:
            continue
        s = res.settings
        raw = s.get("raw") if isinstance(s.get("raw"), dict) else {}
        retry = {k: (_int(v) if _int(v) is not None else v) for k, v in sorted({**raw, **s}.items())
                 if "retry" in k.lower() and not isinstance(v, (dict, list))}
        breaker: dict[str, Any] = {}
        for key, name in (("circuit_breaker_failure_rate", "failure_rate"), ("circuit_breaker_window", "window"),
                          ("circuit_breaker_sleep_ms", "break_ms")):
            if _int(s.get(key)) is not None:
                breaker[name] = _int(s.get(key))
        out[res.id] = ResilienceMap(resource_id=res.id, timeout_ms=_int(s.get("timeout_ms")),
                                    retry=retry or None, breaker=breaker or None)
    return list(out.values())


# ------------------------------------------------------------------- sequence
def _walk_order(p: Process) -> list[tuple[str, Transition | None]]:
    acts = {a.id: a for a in p.activities}
    groups = {g.id: g for g in p.groups}
    out_by: dict[str, list[Transition]] = defaultdict(list)
    incoming: set[str] = set()
    for t in p.transitions:
        out_by[t.from_id].append(t)
        incoming.add(t.to_id)
    visited: set[str] = set()
    order: list[tuple[str, Transition | None]] = []

    def entries(g: Group) -> list[str]:
        e = g.config.get("entry_ids")
        if isinstance(e, list) and e:
            return [str(x) for x in e]
        members = set(g.member_ids)
        inner = {t.to_id for t in p.transitions if t.from_id in members}
        return [m for m in g.member_ids if m not in inner][:1] or g.member_ids[:1]

    def visit(node: str, via: Transition | None) -> bool:
        if node in visited:
            return False
        act = acts.get(node)
        if act is not None and act.group_id in groups and act.group_id not in visited:
            visited.add(act.group_id)
            order.append((act.group_id, None))
        visited.add(node)
        order.append((node, via))
        return True

    def walk(starts: list[tuple[str, Transition | None]]) -> None:
        queue = deque(starts)
        while queue:
            node, via = queue.popleft()
            if not visit(node, via):
                continue
            if node in groups:
                walk([(e, None) for e in entries(groups[node])])
            for t in out_by.get(node, []):
                queue.append((t.to_id, t))

    if p.starter and p.starter.activity_id in acts:
        starts = [p.starter.activity_id]
    else:
        starts = [a.id for a in p.activities if a.id not in incoming] or [a.id for a in p.activities[:1]]
    walk([(s, None) for s in starts])
    for a in p.activities:
        if a.id not in visited:
            walk([(a.id, None)])
    for g in p.groups:
        if g.id not in visited:
            visit(g.id, None)
    return order


def _short(text: str, n: int = 80) -> str:
    text = " ".join(text.split())
    return text if len(text) <= n else text[: n - 3] + "..."


def _sequence(ctx: _Ctx, primary: dict[str, MappingRow]) -> list[SequenceStep]:
    p = ctx.p
    service = f"{ctx.proc_name}Service"
    steps: list[SequenceStep] = []
    st = p.starter
    starter_row = primary.get(st.activity_id) if st else None
    kind = st.kind if st else None
    if st and starter_row and kind in ("rest", "http", "soap", "jms", "timer"):
        c = st.config
        actor, label = {
            "rest": ("Client", f"{str(c.get('verb') or '').upper()} {c.get('path') or ''}".strip()),
            "http": ("Client", f"HTTP {c.get('resource_path') or ''}".strip()),
            "soap": ("Client", f"SOAP {c.get('operation') or p.name}"),
            "jms": ("ServiceBus", str(c.get("destination") or "")),
            "timer": ("Scheduler", str(c.get("interval") or c.get("start") or "schedule")),
        }[kind]
        steps.append(SequenceStep(from_=actor, to=starter_row.class_name, label=f"{label} ({st.activity_id})"))
        steps.append(SequenceStep(from_=starter_row.class_name, to=service, label="ExecuteAsync"))
    else:
        steps.append(SequenceStep(from_="Caller", to=service, label="ExecuteAsync"))
    handlers = {aid: h.fault_name or "all" for h in p.fault_handlers for aid in h.activity_ids}
    for node, via in _walk_order(p):
        if st and node == st.activity_id:
            continue
        row = primary.get(node)
        if row is None:
            continue
        prefix = ""
        if via is not None and via.kind == "conditional":
            prefix = f"[{_short(via.expression or 'when')}] "
        elif via is not None and via.kind in ("otherwise", "error"):
            prefix = f"[{via.kind}] "
        elif node in handlers:
            prefix = f"[catch {handlers[node]}] "
        steps.append(SequenceStep(from_=service, to=row.class_name, label=f"{prefix}{row.method} ({node})"))
    return steps


# ----------------------------------------------------------------- layout
def _layout(ctx: _Ctx, rows: list[MappingRow], contracts: list[Contract]) -> SolutionLayout:
    a, pn = ctx.app_name, ctx.proc_name
    files: dict[str, set[str]] = {k: set() for _, k in _PROJECT_KINDS}
    for _, kind in _PROJECT_KINDS:
        files[kind].add(f"{ctx.project(kind)}.csproj")
    files["api"] |= {"Program.cs", "appsettings.json"}
    files["core"] |= {"Contracts/TibcoPathAttribute.cs", f"Services/{pn}Service.cs"}
    files["core"] |= {csharp_contracts.contract_file(c) for c in contracts}
    files["tests"] |= {f"{pn}RulesTests.cs", f"{pn}BranchTests.cs", f"{pn}ScenarioTests.cs"}
    by_project = {ctx.project(k): k for _, k in _PROJECT_KINDS}
    for r in rows:
        files[by_project[r.project]].add(r.file)
    patterns_used = {r.pattern for r in rows}
    if patterns_used & set(_JMS_TYPES):
        files["core"].add("Messaging/IMessageBus.cs")
        files["infrastructure"] |= {"Messaging/ServiceBusMessageBus.cs", "Messaging/InMemoryMessageBus.cs"}
    if "throw" in patterns_used:
        files["api"].add("Errors/FaultExceptionHandler.cs")
    if patterns_used & {"jdbc.query", "jdbc.update", "jdbc.call"}:
        files["tests"].add("TestDatabase.cs")
    return SolutionLayout(name=a, projects=[ProjectLayout(name=ctx.project(k), kind=k, files=sorted(files[k]))
                                            for _, k in _PROJECT_KINDS])


# --------------------------------------------------------------------- build
def _spec_hash(process: Process, rules: list[Rule], findings: list[Finding]) -> str:
    approved = [r.model_dump(mode="json") for r in rules if r.status in ("approved", "edited")]
    decisions = [{"id": f.id, "decision": f.decision, "note": f.note} for f in findings]
    return compute_spec_hash(process.model_dump(mode="json"), approved, decisions)


def build_design_skeleton(process: Process, app: Application, rules: list[Rule], findings: list[Finding],
                          io_card: IOCard, spec_hash: str | None = None) -> DesignRecord:
    """Deterministic design record for one process; ``narrative`` is left ``None``.

    ``spec_hash`` defaults to ``engine.ir.spec_hash.spec_hash`` over the IR, the approved rules and
    the finding decisions; pass the stored value to bind to a gate record instead.
    """
    ctx = _Ctx(process, app, rules, findings)
    rows: list[MappingRow] = []
    primary: dict[str, MappingRow] = {}
    for act in process.activities:
        act_rows = _activity_rows(ctx, act)
        primary[act.id] = act_rows[0]
        rows += act_rows
    for g in process.groups:
        grow = _group_row(ctx, g)
        if grow:
            primary[g.id] = grow
            rows.append(grow)

    contracts = _process_contracts(process, app, io_card)
    contract_maps = [ContractMap(contract_id=c.id, record_names=csharp_contracts.record_names(c))
                     for c in contracts]

    decisions: list[Decision] = []
    open_questions: list[OpenQuestion] = []
    for r in rows:
        hint = PATTERNS[r.pattern].decision if r.pattern in PATTERNS else None
        if hint and r.pattern != "input.mapping":
            d = Decision(title=f"{hint.title}: {r.activity_name}", choice=hint.choice,
                         alternatives=list(hint.alternatives), reason=f"{hint.reason} {_NOT_A_DECISION}")
            if d not in decisions:
                decisions.append(d)
        if r.pattern == "unknown":
            act = next((a for a in process.activities if a.id == r.activity_id), None)
            native = act.native_type if act else r.canonical_type
            open_questions.append(OpenQuestion(
                question=f"No .NET pattern for native type {native} (step {r.activity_id}).",
                recommendation="Add a catalogue mapping before generation; until then the builder drafts "
                               f"the method and a reviewer checks it. {_NOT_A_DECISION}"))
        if r.pattern == "call.process" and r.activity_id not in ctx.calls:
            open_questions.append(OpenQuestion(
                question=f"Call {r.activity_id} names no target process.",
                recommendation=f"Confirm the subprocess from the TIBCO project. {_NOT_A_DECISION}"))
    for f in findings:
        if f.decision == "ask":
            open_questions.append(OpenQuestion(
                question=f"{f.id}: {f.text}",
                recommendation="Keep the TIBCO behaviour in the generated code and record the business "
                               f"owner's answer before parity sign-off. {_NOT_A_DECISION}"))
        elif f.decision is None:
            open_questions.append(OpenQuestion(
                question=f"{f.id} has no decision: {f.text}",
                recommendation=f"Decide Keep, Fix or Ask at G2 before approving the design. {_NOT_A_DECISION}"))
    owners: dict[str, list[str]] = defaultdict(list)
    for cm in contract_maps:
        for n in cm.record_names:
            owners[n].append(cm.contract_id)
    for n, ids in sorted(owners.items()):
        if len(ids) > 1:
            open_questions.append(OpenQuestion(
                question=f"Record {n} is defined by {', '.join(ids)}.",
                recommendation="Generate one record per contract namespace, or confirm the shapes are the "
                               f"same and keep one. {_NOT_A_DECISION}"))

    expected = [ExpectedDifference(finding_id=f.id, description=f.text + (f" Note: {f.note}" if f.note else ""))
                for f in findings if f.decision == "fix"]

    record = DesignRecord(
        process_id=process.id,
        spec_hash=spec_hash or _spec_hash(process, rules, findings),
        solution=_layout(ctx, rows, contracts),
        mapping=rows,
        contracts=contract_maps,
        config=_config(ctx, _used_resources(process, app)),
        messaging=_messaging(process),
        resilience=_resilience(process, app),
        sequence=_sequence(ctx, primary),
        decisions=decisions,
        open_questions=open_questions,
        expected_differences=expected,
        narrative=None,
    )
    record.design_hash = compute_design_hash(record)
    return record

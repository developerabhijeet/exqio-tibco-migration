// Screenshots of each view for review: BASE_URL=... PROJECT_NAME=... node scripts/screenshots.mjs <out-dir>
// (needs the API and the web app running, and a scanned project; default: the newest project).
import { chromium } from "@playwright/test";
const out = process.argv[2];
const base = process.env.BASE_URL ?? "http://localhost:3000";
const projectName = process.env.PROJECT_NAME;
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
page.on("pageerror", (e) => errors.push(String(e)));
await page.goto(`${base}/`);
await page.waitForTimeout(2500);
if (projectName) {
  await page.getByTestId("project-select").selectOption({ label: projectName });
  await page.waitForTimeout(2000);
}
await page.getByTestId("step-upload").click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/01-upload.png`, fullPage: true });
await page.getByTestId("step-discover").click();
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/02-discover-top.png`, fullPage: false });
await page.getByTestId("domain-select").click();
await page.getByRole("option", { name: /Dealer Funding/ }).click();
await page.waitForTimeout(1500);
await page.getByTestId("process-list").getByRole("button", { name: /DealerFundingRequest/ }).click();
await page.waitForTimeout(2500);
await page.locator('.react-flow__node[data-id="LookupDealer"]').click();
await page.waitForTimeout(800);
await page.getByTestId("process-view").scrollIntoViewIfNeeded();
await page.screenshot({ path: `${out}/03-discover-full.png`, fullPage: true });
await page.getByRole("tab", { name: "XML" }).click();
await page.waitForTimeout(2000);
await page.getByTestId("process-view").screenshot({ path: `${out}/04-canvas-xml.png` });
await page.getByRole("tab", { name: "SQL" }).click();
await page.getByTestId("inspector").screenshot({ path: `${out}/05-inspector-sql.png` });
await page.getByTestId("io-card").screenshot({ path: `${out}/06-io-card.png` });
await page.getByTestId("domain-select").click();
await page.getByRole("option", { name: /Credit Origination/ }).click();
await page.waitForTimeout(1000);
await page.getByTestId("process-list").getByRole("button", { name: /BureauOrchestrator/ }).click();
await page.waitForTimeout(2500);
await page.getByTestId("process-canvas").screenshot({ path: `${out}/07-canvas-groups.png` });
await page.getByTestId("process-list").getByRole("button", { name: /CreditApplicationIntake/ }).click();
await page.waitForTimeout(2500);
await page.getByTestId("process-canvas").screenshot({ path: `${out}/08-canvas-faults.png` });
await page.getByRole("button", { name: "Evidence for Upload" }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/09-evidence.png` });
await page.keyboard.press("Escape");
await page.getByTestId("domain-select").click();
await page.screenshot({ path: `${out}/10-domain-select.png` });
await page.keyboard.press("Escape");
await page.goto(`${base}/settings`);
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/11-settings.png` });
console.log("errors:", JSON.stringify(errors, null, 1));
await browser.close();

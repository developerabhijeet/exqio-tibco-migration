/** The Monaco language of a path, for a file the API reports no language for (an edit preview). */
export function languageOfPath(path: string): string {
  const ext = path.slice(path.lastIndexOf(".") + 1).toLowerCase();
  const byExt: Record<string, string> = {
    cs: "csharp", csproj: "xml", sln: "plaintext", xml: "xml", json: "json", md: "markdown", yml: "yaml",
    yaml: "yaml", tf: "hcl", sh: "shell", ps1: "powershell", sql: "sql", java: "java", go: "go", py: "python",
    ts: "typescript", js: "javascript",
  };
  return monacoLanguage(byExt[ext] ?? "plaintext", path);
}

/**
 * Diff mode: one file of an edit set, the baseline build's version beside the edited one. An added
 * file has an empty left side and a deleted one an empty right side.
 */
export function CodeDiff({
  path,
  baseline,
  edited,
  height = 420,
  testId = "edit-diff",
}: {
  path: string;
  baseline: string;
  edited: string;
  height?: number;
  testId?: string;
}) {
  return (
    <div className="flex min-w-0 flex-col gap-2" data-testid={testId}>
      <div className="flex min-h-[28px] flex-wrap items-center gap-2">
        <FileCode2 size={15} className="text-slate" aria-hidden />
        <span className="min-w-0 truncate font-mono text-[12.5px] font-semibold text-plum">{path}</span>
        <span className="ml-auto text-[12px] text-slate">baseline build, left; edited, right</span>
      </div>
      <DiffView original={baseline} modified={edited} language={languageOfPath(path)} height={height} />
    </div>
  );
}

const ORIGIN: Record<string, { tone: "det" | "ai" | "decision" | "purple"; title: string }> = {
  code: { tone: "det", title: "Written by code from the design record" },
  ai: { tone: "ai", title: "Body filled by the Code Builder model and accepted by the code checks" },
  agent: { tone: "decision", title: "Left for a model: the placeholder is still in the file" },
  infra: { tone: "purple", title: "Infrastructure generated by code" },
  hand: { tone: "decision", title: "Edited by hand and applied from an edit set; no model or repair may change it" },
};

/** Monaco languages for the file kinds the API reports. */
function monacoLanguage(language: string, path: string): string {
  if (path.endsWith("Dockerfile") || path.endsWith(".dockerignore")) return "dockerfile";
  if (language === "plaintext" && path.endsWith(".sh")) return "shell";
  return language;
}

export function OriginPill({ origin, testId }: { origin: string; testId?: string }) {
  const o = ORIGIN[origin] ?? { tone: "det" as const, title: origin };
  return (
    <Pill tone={o.tone} title={o.title} testId={testId}>
      {origin}
    </Pill>
  );
}

/** The selected generated file: path, origin, the TIBCO steps it implements, then the code, at
 * `line` when one is asked for. */
export function CodeViewer({
  buildId,
  entry,
  empty = "Select a generated file, or a step on the TIBCO canvas, to see its code here.",
  testId = "code-viewer",
  showRef = true,
  height = 520,
  line = null,
  lineRequest = 0,
}: {
  buildId: string;
  entry: BuildFileEntry | null;
  empty?: string;
  testId?: string;
  /** false when the caller shows the TIBCO steps itself (the source and target explorer). */
  showRef?: boolean;
  height?: number;
  /** A 1-based line to highlight and scroll to (a citation chip's file and line). */
  line?: number | null;
  /** Which request asked for `line` (a click's time): a new request reveals the line again even
   * when it is the same line. */
  lineRequest?: number;
}) {
  const { jumpToStep, processId } = useAppState();
  const file = useBuildFile(buildId, entry?.path ?? null);
  // Memoised per request: a new object each render would scroll the editor back to the line every
  // time, while a new click on the same chip must scroll to it again.
  // eslint-disable-next-line react-hooks/exhaustive-deps
  const highlight = useMemo(() => (line && line > 0 ? { start: line, end: line, focus: line } : null), [line, lineRequest]);
  if (!entry) {
    return (
      <div
        data-testid={`${testId}-empty`}
        style={{ minHeight: height }}
        className="flex h-full items-center justify-center rounded-btn border border-dashed border-line bg-sunken/60 p-6 text-center text-md text-slate"
      >
        {empty}
      </div>
    );
  }
  const ref = entry.tibco_ref;
  return (
    <div className="flex min-w-0 flex-col gap-2" data-testid={testId}>
      <div className="flex min-h-[28px] flex-wrap items-center gap-2">
        <FileCode2 size={15} className="text-slate" aria-hidden />
        <span data-testid="code-path" className="min-w-0 truncate font-mono text-sm font-semibold text-heading">
          {entry.path}
        </span>
        <OriginPill origin={entry.origin} testId="origin-pill" />
        {entry.origin === "hand" ? <HandBadge /> : null}
        {file.data ? <span className="text-xs text-slate">{file.data.language}</span> : null}
        <span className="ml-auto text-xs text-slate">{formatBytes(entry.size)}</span>
      </div>
      {showRef ? (
        <div data-testid="tibco-ref" className="rounded-btn border border-line bg-page px-3 py-2 text-sm">
          {ref ? (
            <>
              <p>
                <span className="label mr-1.5">TIBCO source</span>
                <span className="font-mono">{ref.source_path}</span>
              </p>
              <ul className="mt-1 flex min-w-0 flex-wrap gap-1.5">
                {ref.rows.map((r) => (
                  <li key={`${r.activity_id}:${r.method}`}>
                    <button
                      type="button"
                      title={`Line ${ref.source_lines[r.activity_id] ?? "?"} of the process; open it on the canvas`}
                      onClick={() => jumpToStep(r.activity_id, processId)}
                      className="inline-flex max-w-full flex-wrap items-center gap-x-1 rounded-full border border-line bg-surface px-2 py-0.5 text-left hover:border-accent hover:text-accent-ink"
                    >
                      <Crosshair size={11} aria-hidden />
                      <span className="font-medium">{r.activity_name}</span>
                      <span className="text-slate">
                        {r.class_name}.{r.method}
                      </span>
                      {ref.source_lines[r.activity_id] ? (
                        <span className="text-slate">line {ref.source_lines[r.activity_id]}</span>
                      ) : null}
                      {r.rule_ids.length ? <span className="text-gate">{r.rule_ids.join(", ")}</span> : null}
                    </button>
                  </li>
                ))}
              </ul>
            </>
          ) : (
            <p className="text-slate">
              No TIBCO step: {entry.origin === "infra" ? "infrastructure for the whole solution" : "shared by every workflow in the solution"}.
            </p>
          )}
        </div>
      ) : null}
      {file.error ? <ErrorNote error={file.error} /> : null}
      {file.data ? (
        <CodeView
          value={file.data.content}
          language={monacoLanguage(file.data.language, entry.path)}
          height={height}
          highlight={highlight}
          testId={`${testId}-editor`}
        />
      ) : file.isLoading ? (
        <div style={{ height }} className="rounded-btn border border-line bg-page p-4 text-sm text-slate">
          Loading file
        </div>
      ) : null}
    </div>
  );
}
